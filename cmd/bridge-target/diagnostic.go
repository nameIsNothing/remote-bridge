package main

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"

	"remote-bridge/internal/diagnostic"
)

var targetDiagnostics struct {
	sync.RWMutex
	logger *diagnostic.Logger
	err    error
}

func openTargetDiagnostic(directory, mode string) error {
	logger, err := diagnostic.New(diagnostic.Options{Directory: directory, Filename: "bridge-target.jsonl", Version: version, Mode: mode})
	targetDiagnostics.Lock()
	targetDiagnostics.logger, targetDiagnostics.err = logger, err
	targetDiagnostics.Unlock()
	return err
}

func initializeTargetDiagnostics(args []string) {
	mode := "gui"
	if len(args) > 0 {
		mode = strings.ToLower(args[0])
	}
	switch mode {
	case "version", "--version", "-v", "help", "--help", "-h", "ssh-service", "ssh-unix-host", "ssh-unix-session", "ssh-unix-run":
		// The service initializes only after its SCM/SYSTEM ownership checks.
		return
	case "gui", "ssh", "winrm", "inspect", "check", "plan", "apply", "--apply", "revoke", "rollback":
	default:
		// Unknown arguments may contain sensitive input; never use them as metadata.
		mode = "cli"
	}
	program, err := os.Executable()
	if err == nil {
		err = openTargetDiagnostic(filepath.Join(filepath.Dir(program), "logs"), mode)
	}
	if err != nil {
		cache, cacheErr := os.UserCacheDir()
		if cacheErr == nil {
			cacheErr = openTargetDiagnostic(filepath.Join(cache, "RemoteBridge", "logs"), mode)
		}
		if cacheErr != nil {
			targetDiagnostics.Lock()
			targetDiagnostics.err = errors.Join(err, cacheErr)
			targetDiagnostics.Unlock()
		} else {
			targetDiagnostic(diagnostic.Event{Level: "warning", Event: "log.fallback", Error: err.Error(), Message: "程序目录不可写，日志已改存到用户目录"})
		}
	}
	targetDiagnostic(diagnostic.Event{Event: "program.started", Message: "目标程序已启动"})
}

func targetDiagnostic(event diagnostic.Event) {
	targetDiagnostics.RLock()
	logger := targetDiagnostics.logger
	targetDiagnostics.RUnlock()
	if logger == nil {
		return
	}
	if err := logger.Log(event); err != nil {
		targetDiagnostics.Lock()
		targetDiagnostics.err = err
		targetDiagnostics.Unlock()
	}
}

func registerTargetDiagnosticSecret(secret string) {
	targetDiagnostics.RLock()
	logger := targetDiagnostics.logger
	targetDiagnostics.RUnlock()
	if logger != nil {
		logger.AddSecret(secret)
	}
}

func targetDiagnosticLocation() (string, string) {
	targetDiagnostics.RLock()
	defer targetDiagnostics.RUnlock()
	path := ""
	if targetDiagnostics.logger != nil {
		path = targetDiagnostics.logger.Path()
	}
	if targetDiagnostics.err != nil {
		return path, diagnostic.Sanitize(targetDiagnostics.err.Error())
	}
	return path, ""
}

func safeTargetDiagnosticText(value string) string {
	targetDiagnostics.RLock()
	logger := targetDiagnostics.logger
	targetDiagnostics.RUnlock()
	if logger == nil {
		return diagnostic.Sanitize(value)
	}
	return logger.Sanitize(value)
}

func runWithDiagnostics(args []string) (code int) {
	initializeTargetDiagnostics(args)
	defer func() {
		if failure := recover(); failure != nil {
			code = 50
			targetDiagnostic(diagnostic.Event{Level: "error", Event: "program.panic", Error: fmt.Sprint(failure)})
		}
		targetDiagnostic(diagnostic.Event{Event: "program.exited", ExitCode: &code})
	}()
	return run(args)
}

// Copy host-side structured errors into the portable controller log before
// rollback removes the protected runtime. This does not read SSH keys,
// authorized_keys, configuration, command output or raw SSH session traffic.
func captureSSHHostDiagnostics(r *sshTargetRuntime) {
	if r == nil || !validSSHPlanID(r.id) || !samePath(r.root, sshRuntimeDirectory(r.id)) {
		return
	}
	path := filepath.Join(r.root, "logs", "bridge-target.jsonl")
	if err := validateSSHOwnedPath(path); err != nil {
		return
	}
	file, err := os.Open(path)
	if err != nil {
		return
	}
	defer file.Close()
	// Host diagnostics are structured metadata generated by this program.
	captureDiagnosticRecords(file, r.id)
}

func captureDiagnosticRecords(reader io.Reader, instance string) {
	scanner := bufio.NewScanner(io.LimitReader(reader, 1<<20))
	scanner.Buffer(make([]byte, 4096), 64<<10)
	count := 0
	for scanner.Scan() && count < 64 {
		var event diagnostic.Event
		if json.Unmarshal(scanner.Bytes(), &event) != nil || event.Event == "" {
			continue
		}
		if event.Level != "error" && event.Level != "warning" {
			continue
		}
		event.Event, event.Instance = "host."+event.Event, instance
		targetDiagnostic(event)
		count++
	}
}
